const escapeAttr = (value: unknown) => String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function toMarkup(node: IconNode): string {
  return node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([key, value]) => `${key}="${escapeAttr(value)}"`).join(' ')}/>`)
    .join('');
}

const MARKUP = new Map(Object.entries(ICONS).map(([name, node]) => [name, toMarkup(node)]));

@Component({
  selector: 'app-icon',
  changeDetection: ChangeDetectionStrategy.OnPush,
  host: { class: 'glyph', 'aria-hidden': 'true' },
  template: `<svg viewBox="0 0 24 24" [innerHTML]="markup()"></svg>`,
})
export class Icon {
  private readonly sanitizer = inject(DomSanitizer);
  readonly name = input.required<string>();
  // The markup comes only from the bundled Lucide icon data above, never from user input.
  protected readonly markup = computed(() => this.sanitizer.bypassSecurityTrustHtml(MARKUP.get(this.name()) ?? ''));
}
